-- +goose Up
CREATE TABLE manage_role (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(64)  NOT NULL DEFAULT '',
    code       varchar(64)  NOT NULL DEFAULT '',    -- 角色标识, superadmin 为超管
    remark     varchar(255) NOT NULL DEFAULT '',
    status     smallint     NOT NULL DEFAULT 1,
    created_at timestamptz  NOT NULL DEFAULT now(),
    updated_at timestamptz  NOT NULL DEFAULT now()
);
COMMENT ON TABLE manage_role IS '总后台角色';

CREATE TABLE manage_admin (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      varchar(64) NOT NULL DEFAULT '',
    password      varchar(64) NOT NULL DEFAULT '',   -- 历史: md5(pwd+salt); 见 00007 升级为 bcrypt
    salt          varchar(32) NOT NULL DEFAULT '',   -- 历史字段; bcrypt 后可为空
    nickname      varchar(64) NOT NULL DEFAULT '',
    role_id       bigint      NOT NULL DEFAULT 0,
    status        smallint    NOT NULL DEFAULT 1,
    last_login_at timestamptz,
    last_ip       varchar(64) NOT NULL DEFAULT '',
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uk_manage_admin_username ON manage_admin (username);
COMMENT ON TABLE manage_admin IS '总后台管理员';

CREATE TABLE casbin_rule (
    id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ptype varchar(100) NOT NULL DEFAULT '',
    v0    varchar(100) NOT NULL DEFAULT '',
    v1    varchar(100) NOT NULL DEFAULT '',
    v2    varchar(100) NOT NULL DEFAULT '',
    v3    varchar(100) NOT NULL DEFAULT '',
    v4    varchar(100) NOT NULL DEFAULT '',
    v5    varchar(100) NOT NULL DEFAULT ''
);
COMMENT ON TABLE casbin_rule IS 'Casbin 权限策略(总后台)';

CREATE TABLE manage_log (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id   bigint       NOT NULL DEFAULT 0,
    method     varchar(16)  NOT NULL DEFAULT '',
    path       varchar(255) NOT NULL DEFAULT '',
    ip         varchar(64)  NOT NULL DEFAULT '',
    created_at timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX idx_manage_log_admin ON manage_log (admin_id, created_at);
COMMENT ON TABLE manage_log IS '总后台操作日志';

