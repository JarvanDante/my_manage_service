-- 平台服务配置发布记录(每个服务×环境自增版本; 回滚=重发历史版本原文)。
-- +goose Up
CREATE TABLE service_config_publish (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service    varchar(32)  NOT NULL,                 -- media/storage/play/ad
    env        varchar(8)   NOT NULL DEFAULT 'dev',   -- dev/test/prod
    version    int          NOT NULL DEFAULT 1,       -- 服务×环境内自增
    content    text         NOT NULL DEFAULT '',      -- 发布的 YAML 原文
    operator   bigint       NOT NULL DEFAULT 0,       -- 发布管理员ID
    remark     varchar(255) NOT NULL DEFAULT '',
    created_at timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uk_svccfg_service_env_version ON service_config_publish (service, env, version);
COMMENT ON TABLE service_config_publish IS '平台服务配置发布记录';

