CREATE TABLE merchant (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(64)  NOT NULL DEFAULT '',   -- 商户名(唯一)
    contact    varchar(64)  NOT NULL DEFAULT '',   -- 联系人
    phone      varchar(32)  NOT NULL DEFAULT '',   -- 联系电话/微信
    status     smallint     NOT NULL DEFAULT 1,    -- 1启用 0停用
    remark     varchar(255) NOT NULL DEFAULT '',
    created_at timestamptz  NOT NULL DEFAULT now(),
    updated_at timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uk_merchant_name ON merchant (name);
