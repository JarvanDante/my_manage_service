-- M3: 站点配置发布记录(存"未注入 database 段"的原文, 发布/回滚时动态注入登记的DB信息)。
-- +goose Up
CREATE TABLE site_config_publish (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id    bigint      NOT NULL,
    env        varchar(8)  NOT NULL DEFAULT 'dev',
    version    int         NOT NULL DEFAULT 1,      -- 站点内自增版本
    content    text        NOT NULL DEFAULT '',     -- 原文(不含渲染后的DB密码)
    operator   bigint      NOT NULL DEFAULT 0,      -- 发布管理员ID
    remark     varchar(255) NOT NULL DEFAULT '',    -- 如"回滚自 v2"
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uk_scp_site_version ON site_config_publish (site_id, version);
COMMENT ON TABLE site_config_publish IS '站点配置发布记录';

