-- M2: 站点 + 域名分配。db_pass 用 AES 加密存(kit.Encrypt, 密钥 env MANAGE_SECRET)。
-- +goose Up
CREATE TABLE site (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id bigint       NOT NULL DEFAULT 0,
    site_code   varchar(32)  NOT NULL,              -- 全局唯一; Nacos dataId 前缀 / 前台 host 识别标识
    name        varchar(64)  NOT NULL DEFAULT '',
    env         varchar(8)   NOT NULL DEFAULT 'dev', -- dev / test / prod
    status      smallint     NOT NULL DEFAULT 0,    -- 0筹备 1上线 2停用
    db_host     varchar(128) NOT NULL DEFAULT '',
    db_port     int          NOT NULL DEFAULT 5432,
    db_name     varchar(64)  NOT NULL DEFAULT '',
    db_user     varchar(64)  NOT NULL DEFAULT '',
    db_pass     varchar(512) NOT NULL DEFAULT '',   -- AES-GCM 加密后的 base64
    remark      varchar(255) NOT NULL DEFAULT '',
    created_at  timestamptz  NOT NULL DEFAULT now(),
    updated_at  timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uk_site_code ON site (site_code);
CREATE INDEX idx_site_merchant ON site (merchant_id);
COMMENT ON TABLE site IS '站点(一站一部署一库)';

CREATE TABLE site_domain (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id    bigint       NOT NULL,
    domain     varchar(128) NOT NULL,               -- 全局唯一
    is_main    smallint     NOT NULL DEFAULT 0,     -- 1主域名
    https      smallint     NOT NULL DEFAULT 1,
    status     smallint     NOT NULL DEFAULT 1,
    created_at timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uk_site_domain ON site_domain (domain);
CREATE INDEX idx_site_domain_site ON site_domain (site_id);
COMMENT ON TABLE site_domain IS '站点域名分配';

-- +goose Down
DROP TABLE IF EXISTS site_domain;
DROP TABLE IF EXISTS site;
