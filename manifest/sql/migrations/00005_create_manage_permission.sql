-- M-RBAC: 菜单驱动 RBAC。manage_permission 统一存放「菜单」与「接口权限」的树;
-- manage_role.permissions 存该角色勾选的权限 id 列表(逗号分隔)。取代 casbin。
-- +goose Up
CREATE TABLE manage_permission (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id    bigint       NOT NULL DEFAULT 0,
    name         varchar(64)  NOT NULL DEFAULT '',   -- 菜单/权限名称
    route_url    varchar(255) NOT NULL DEFAULT '',   -- 菜单:前端路由;接口权限:后端API路径(支持 {id} 通配)
    component    varchar(255) NOT NULL DEFAULT '',   -- 菜单叶子:视图路径(相对 views,不含.vue);目录/接口为空
    method       varchar(16)  NOT NULL DEFAULT '',   -- 接口权限:GET/POST/PUT/DELETE;菜单为空
    icon         varchar(64)  NOT NULL DEFAULT '',
    is_menu      smallint     NOT NULL DEFAULT 1,     -- 1=菜单 0=接口权限
    hide_in_menu smallint     NOT NULL DEFAULT 0,     -- 1=是路由但不在侧边栏显示
    affix_tab    smallint     NOT NULL DEFAULT 0,     -- 1=固定标签(如仪表盘)
    active_path  varchar(255) NOT NULL DEFAULT '',   -- 隐藏页高亮的菜单路径
    sort         int          NOT NULL DEFAULT 0,
    status       smallint     NOT NULL DEFAULT 1,     -- 1=启用 0=禁用
    created_at   timestamptz  NOT NULL DEFAULT now(),
    updated_at   timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX idx_manage_permission_parent ON manage_permission (parent_id);
COMMENT ON TABLE manage_permission IS '总后台菜单+接口权限树';

ALTER TABLE manage_role ADD COLUMN permissions text NOT NULL DEFAULT '';
COMMENT ON COLUMN manage_role.permissions IS '该角色勾选的权限id列表,逗号分隔';

