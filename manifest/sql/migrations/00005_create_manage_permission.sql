-- M-RBAC: 菜单驱动 RBAC。manage_permission 统一存放「菜单」与「接口权限」的树;
-- manage_role.permissions 存该角色勾选的权限 id 列表(逗号分隔)。取代 casbin。
-- 全部使用显式 id,末尾 setval 修正序列,避免自增与显式 id 冲突;可重复执行。
-- +goose Up
CREATE TABLE IF NOT EXISTS manage_permission (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id    bigint       NOT NULL DEFAULT 0,
    name         varchar(64)  NOT NULL DEFAULT '',
    route_url    varchar(255) NOT NULL DEFAULT '',
    component    varchar(255) NOT NULL DEFAULT '',
    method       varchar(16)  NOT NULL DEFAULT '',
    icon         varchar(64)  NOT NULL DEFAULT '',
    is_menu      smallint     NOT NULL DEFAULT 1,
    hide_in_menu smallint     NOT NULL DEFAULT 0,
    affix_tab    smallint     NOT NULL DEFAULT 0,
    active_path  varchar(255) NOT NULL DEFAULT '',
    sort         int          NOT NULL DEFAULT 0,
    status       smallint     NOT NULL DEFAULT 1,
    created_at   timestamptz  NOT NULL DEFAULT now(),
    updated_at   timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_manage_permission_parent ON manage_permission (parent_id);
COMMENT ON TABLE manage_permission IS '总后台菜单+接口权限树';

ALTER TABLE manage_role ADD COLUMN IF NOT EXISTS permissions text NOT NULL DEFAULT '';
COMMENT ON COLUMN manage_role.permissions IS '该角色勾选的权限id列表,逗号分隔';

